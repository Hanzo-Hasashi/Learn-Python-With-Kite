BEGIN;

CREATE TABLE IF NOT EXISTS public.subscription_plans (
    id VARCHAR(40) PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    display_price VARCHAR(40) NOT NULL,
    amount VARCHAR(20) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'ZMW',
    period VARCHAR(20),
    premium BOOLEAN NOT NULL DEFAULT FALSE,
    summary VARCHAR(300) NOT NULL,
    features_json TEXT NOT NULL DEFAULT '[]',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.subscription_registrations (
    id VARCHAR(36) PRIMARY KEY,
    user_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    plan_id VARCHAR(40) NOT NULL REFERENCES public.subscription_plans(id),
    idempotency_key VARCHAR(36) NOT NULL UNIQUE,
    request_hash VARCHAR(64) NOT NULL,
    access_key_hash VARCHAR(64) NOT NULL,
    phone_ciphertext TEXT NOT NULL,
    phone_hash VARCHAR(64) NOT NULL,
    phone_last4 VARCHAR(4) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING_PAYMENT'
        CONSTRAINT ck_subscription_registration_status
        CHECK (status IN ('PENDING_PAYMENT', 'ACTIVE', 'EXPIRED', 'CANCELLED', 'FAILED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_subscription_registrations_user_id
    ON public.subscription_registrations (user_id);
CREATE INDEX IF NOT EXISTS ix_subscription_registrations_plan_id
    ON public.subscription_registrations (plan_id);
CREATE INDEX IF NOT EXISTS ix_subscription_registrations_phone_hash
    ON public.subscription_registrations (phone_hash);
CREATE INDEX IF NOT EXISTS ix_subscription_registrations_status
    ON public.subscription_registrations (status);

CREATE TABLE IF NOT EXISTS public.payment_transactions (
    id VARCHAR(36) PRIMARY KEY,
    registration_id VARCHAR(36) NOT NULL
        REFERENCES public.subscription_registrations(id) ON DELETE CASCADE,
    subscription_id INTEGER REFERENCES public.subscriptions(id) ON DELETE SET NULL,
    reference VARCHAR(64) NOT NULL UNIQUE,
    provider_id VARCHAR(80),
    provider_reference VARCHAR(160),
    amount VARCHAR(20) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'NOT_INITIATED'
        CONSTRAINT ck_payment_transaction_status
        CHECK (status IN ('NOT_INITIATED', 'PENDING', 'PROCESSING', 'SUCCESSFUL', 'FAILED', 'CANCELLED', 'EXPIRED')),
    failure_code VARCHAR(80),
    expires_at TIMESTAMPTZ,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_payment_transactions_registration_id
    ON public.payment_transactions (registration_id);
CREATE INDEX IF NOT EXISTS ix_payment_transactions_subscription_id
    ON public.payment_transactions (subscription_id);
CREATE INDEX IF NOT EXISTS ix_payment_transactions_provider_id
    ON public.payment_transactions (provider_id);
CREATE INDEX IF NOT EXISTS ix_payment_transactions_provider_reference
    ON public.payment_transactions (provider_reference);
CREATE INDEX IF NOT EXISTS ix_payment_transactions_status
    ON public.payment_transactions (status);

CREATE TABLE IF NOT EXISTS public.payment_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(36) NOT NULL
        REFERENCES public.payment_transactions(id) ON DELETE CASCADE,
    attempt_number INTEGER NOT NULL CONSTRAINT ck_payment_attempt_number CHECK (attempt_number > 0),
    idempotency_key VARCHAR(36) NOT NULL UNIQUE,
    provider_id VARCHAR(80) NOT NULL,
    status VARCHAR(24) NOT NULL
        CONSTRAINT ck_payment_attempt_status
        CHECK (status IN ('NOT_INITIATED', 'PENDING', 'PROCESSING', 'SUCCESSFUL', 'FAILED', 'CANCELLED', 'EXPIRED')),
    failure_code VARCHAR(80),
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT uq_payment_attempt_number UNIQUE (transaction_id, attempt_number)
);

CREATE INDEX IF NOT EXISTS ix_payment_attempts_transaction_id
    ON public.payment_attempts (transaction_id);

CREATE TABLE IF NOT EXISTS public.payment_status_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(36) NOT NULL
        REFERENCES public.payment_transactions(id) ON DELETE CASCADE,
    previous_status VARCHAR(24),
    status VARCHAR(24) NOT NULL
        CONSTRAINT ck_payment_status_history_status
        CHECK (status IN ('NOT_INITIATED', 'PENDING', 'PROCESSING', 'SUCCESSFUL', 'FAILED', 'CANCELLED', 'EXPIRED')),
    source VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_payment_status_history_transaction_id
    ON public.payment_status_history (transaction_id);

CREATE TABLE IF NOT EXISTS public.payment_provider_configurations (
    provider_id VARCHAR(80) PRIMARY KEY,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    environment VARCHAR(20) NOT NULL DEFAULT 'sandbox'
        CONSTRAINT ck_payment_provider_environment
        CHECK (environment IN ('sandbox', 'production')),
    options_json TEXT NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
DECLARE
    table_name TEXT;
    role_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'subscription_plans',
        'subscription_registrations',
        'payment_transactions',
        'payment_attempts',
        'payment_status_history',
        'payment_provider_configurations'
    ]
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM PUBLIC', table_name);
        FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated']
        LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
                EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM %I', table_name, role_name);
            END IF;
        END LOOP;
    END LOOP;
END
$$;

COMMIT;
