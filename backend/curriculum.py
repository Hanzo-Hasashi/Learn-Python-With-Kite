def _question(question: str, options: tuple[str, ...], answer: int,
              explanation: str, code: str | None = None,
              question_type: str | None = None) -> dict[str, Any]:
    result: dict[str, Any] = {
        "question": question,
        "options": list(options),
        "answer": answer,
        "explanation": explanation,
    }
    if question_type is None:
        normalized = question.casefold()
        if code:
            question_type = "output_prediction" if any(
               phrase in normalized for phrase in ("output", "print", "printed")
            ) else "code_interpretation"
        elif "error" in normalized or "exception" in normalized:
            question_type = "error_identification"
        else:
            question_type = "multiple_choice"
    result["type"] = question_type
    if code:
        result["code"] = code
    return result


