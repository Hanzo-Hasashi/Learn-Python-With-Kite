def _walkthrough(example: str) -> str:
    explanations = []
    for number, line in enumerate(example.splitlines(), start=1):
        source = line.strip()
        if not source:
            continue
        if source.startswith("#"):
            note = "This comment documents intent; Python does not execute it."
        elif source.startswith("import ") or source.startswith("from "):
            note = "This makes the named library functionality available to the following code."
        elif source.startswith("def "):
            note = "This defines a function; its indented body runs when the function is called."
        elif source.startswith("class "):
            note = "This begins a class definition that groups related data and behavior."
        elif source.startswith("for "):
            note = "This starts a loop; Python assigns the next item before running the indented body."
        elif source.startswith("while "):
            note = "Python checks this condition before each iteration and stops when it becomes false."
        elif source.startswith("if ") or source.startswith("elif "):
            note = "Python evaluates this condition and runs the indented branch only when it is true."
        elif source.startswith("else:"):
            note = "This branch runs only when the preceding condition or try operation did not succeed."
        elif source.startswith("try:"):
            note = "This marks the operation whose expected failures are handled below."
        elif source.startswith("except "):
            note = "This handles only the named failure type raised by the try block."
        elif source.startswith("with "):
            note = "This enters a managed context and guarantees its cleanup when the block ends."
        elif source.startswith("return "):
            note = "This sends a value back to the caller and ends the current function call."
        elif source.startswith("yield "):
            note = "This produces one value and pauses the generator until the next iteration."
        elif source.startswith("print("):
            note = "Python evaluates the arguments and writes their readable values to standard output."
        elif "=" in source and "==" not in source and not source.startswith("assert "):
            name = source.split("=", 1)[0].strip()
            note = f"Python evaluates the right-hand expression, then binds its value to {name}."
        elif source.startswith("assert "):
            note = "This checks a development-time invariant and raises AssertionError if it is false."
        else:
            note = "This statement uses the current values to perform the operation shown."
        explanations.append(f"{number}. `{source}` — {note}")
    return "\n".join(explanations)


def _lesson(module_id: str, position: int, spec: tuple[str, ...], order: int,
            *, lesson_id: str | None = None, premium: bool = True,
            xp: int = 30) -> tuple:
    (slug, title, description, objective, syntax, example, expected,
     application, mistake, practice, *authored_walkthrough) = spec
    walkthrough = authored_walkthrough[0] if authored_walkthrough else _walkthrough(example)
    module = MODULE_BY_ID[module_id]
    content = (
        "Learning objectives\n"
        f"- Define {title.lower()} and explain when it is useful.\n"
        "- Trace how Python evaluates the example and predict its output.\n"
        "- Apply the pattern in a small program and check it with the practice task.\n\n"
        "Core concept\n"
        f"Definition: {title} is a Python concept used to solve a recurring programming problem. "
        f"In this lesson, {objective}\n\n"
        "Why it matters\n"
        f"{application} Understanding the underlying rule helps you choose the right tool rather "
        "than copying syntax without knowing what it does.\n\n"
        "How it works\n"
        "Python executes statements in order. It evaluates expressions to produce values, applies "
        "the construct described here, and makes the resulting value or control-flow decision "
        "available to the next statement. Keep the inputs, the operation, and the observable result "
        "separate as you read a program.\n\n"
        "Syntax\n"
        f"{syntax}\n\n"
        "Read the syntax\n"
        "Read punctuation and indentation as part of the language, not decoration. Names identify "
        "values, expressions compute values, and a colon introduces an indented suite when the "
        "construct requires one. Use the exact form above as a starting pattern, then replace its "
        "example names and values with your own.\n\n"
        "Worked example\n"
        f"{example}\n\n"
        "Step-by-step walkthrough\n"
        f"{walkthrough}\n\n"
        "Expected output\n"
        f"{expected}\n\n"
        "Understand the result\n"
        "Compare the displayed result with the values in the example. Python does not guess the "
        "intended answer: the output follows from the values, evaluation order, and rules described "
        "above. If your prediction differs, trace each expression from its inputs before changing code.\n\n"
        "Practical application\n"
        f"{application}\n\n"
        "Common mistakes\n"
        f"{mistake} Check the value and type at the point where it is used, and make the smallest "
        "correction that preserves the program's intention.\n\n"
        "Practice exercises\n"
        f"1. {practice}\n"
        f"2. Change one input in the worked example, predict the new result, then run the code to "
        "check your reasoning.\n\n"
        "Knowledge check\n"
        f"What problem does {title.lower()} solve? Which part of the example demonstrates the rule, "
        "and what would you change to handle a different input?"
    )
    lesson_id = lesson_id or module_id + "-" + slug
    LESSON_MODULES[lesson_id] = (module_id, position)
    return (lesson_id, title, description, content, order, premium, xp)


